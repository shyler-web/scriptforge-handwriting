#!/usr/bin/env node
/**
 * Builds a static Tailwind CSS bundle for ScriptForge.
 *
 * The Play CDN (cdn.tailwindcss.com) compiles utilities at runtime, which
 * means the whole UI depends on a network fetch and Tailwind refuses to run
 * in production. This script performs that compilation once, offline, and
 * writes the result to assets/styles/tailwind.css.
 *
 * Usage: node scripts/build-tailwind.mjs
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const TAILWIND_PKG = process.env.TAILWIND_PKG ||
  '/home//.npm/_npx/23232c69e5d221f3/node_modules/tailwindcss';

const { compile } = await import(join(TAILWIND_PKG, 'dist/lib.mjs'));

function walk(dir, out = []) {
  for (const entry of readdirSync(dir)) {
    if (entry === 'node_modules' || entry === '.git' || entry === 'graphify-out') continue;
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) walk(full, out);
    else if (/\.(html|js)$/.test(entry)) out.push(full);
  }
  return out;
}

/** Pull every utility candidate out of class="..." attributes and classList.add() calls. */
function collectCandidates(files) {
  const candidates = new Set();
  for (const file of files) {
    const src = readFileSync(file, 'utf8');
    for (const m of src.matchAll(/class\s*=\s*["'`]([^"'`]+)["'`]/g)) {
      for (const cls of m[1].split(/\s+/)) {
        if (cls && !cls.includes('${')) candidates.add(cls);
      }
    }
    for (const m of src.matchAll(/classList\.(?:add|remove|toggle)\(\s*["'`]([^"'`]+)["'`]/g)) {
      for (const cls of m[1].split(/\s+/)) {
        if (cls && !cls.includes('${')) candidates.add(cls);
      }
    }
    for (const m of src.matchAll(/className\s*=\s*["'`]([^"'`]+)["'`]/g)) {
      for (const cls of m[1].split(/\s+/)) {
        if (cls && !cls.includes('${')) candidates.add(cls);
      }
    }
  }
  return [...candidates];
}

const sources = walk(ROOT);
const candidates = collectCandidates(sources);

const loadStylesheet = async (id, base) => {
  if (id === 'tailwindcss') {
    return {
      path: join(TAILWIND_PKG, 'index.css'),
      base: dirname(join(TAILWIND_PKG, 'index.css')),
      content: readFileSync(join(TAILWIND_PKG, 'index.css'), 'utf8'),
    };
  }
  const direct = resolve(base, id);
  try {
    return { path: direct, base: dirname(direct), content: readFileSync(direct, 'utf8') };
  } catch {
    return { path: direct, base: dirname(direct), content: `@import "${id}";` };
  }
};

const compiler = await compile('@import "tailwindcss";', {
  base: ROOT,
  loadStylesheet,
  async loadModule() { return { path: 'unused', base: ROOT, content: '' }; },
});

const css = compiler.build(candidates);
const banner = `/* Generated by scripts/build-tailwind.mjs - do not edit by hand. */\n`;
writeFileSync(join(ROOT, 'assets/styles/tailwind.css'), banner + css, 'utf8');

console.log(`candidates: ${candidates.length}`);
console.log(`css bytes:  ${css.length}`);
console.log('written:    assets/styles/tailwind.css');
